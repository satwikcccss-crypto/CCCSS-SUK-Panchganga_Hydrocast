#!/usr/bin/env python
"""
scripts/bootstrap_env.py
========================
Generate a local ``.env`` (backend) and ``frontend/.env.local`` with strong,
random secrets derived from ``.env.example``.

Both output files are git-ignored. This script never prints full secrets: it
prints a masked summary so the values can be checked without leaking into shell
history or CI logs.

Usage
-----
    python scripts/bootstrap_env.py                 # create if missing
    python scripts/bootstrap_env.py --add-missing   # fill gaps, keep existing
    python scripts/bootstrap_env.py --force         # rotate everything

Secrets generated here
----------------------
POSTGRES_PASSWORD, API_KEY, INTERNAL_KEY, JWT_SECRET, ADMIN_PASSWORD,
VISIT_HASH_SALT, TELEGRAM_WEBHOOK_SECRET, HYDROCAST_READONLY_KEY, JUPYTER_TOKEN

External credentials (Telegram bot token, SMTP, Supabase, Upstash, ECMWF) are
left blank / commented — you must obtain those from the provider.
"""

from __future__ import annotations

import argparse
import re
import secrets
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
ENV_EXAMPLE = ROOT / ".env.example"
ENV_FILE = ROOT / ".env"
FRONTEND_ENV = ROOT / "frontend" / ".env.local"


def tok(nbytes: int = 32) -> str:
    """URL-safe secret with no quoting hazards in .env or connection URLs."""
    return secrets.token_urlsafe(nbytes)


def mask(value: str) -> str:
    if len(value) <= 8:
        return "****"
    return f"{value[:4]}...{value[-4:]} (len={len(value)})"


def build_backend_env(template: str) -> tuple[str, dict[str, str]]:
    secrets_map = {
        "POSTGRES_PASSWORD": tok(24),
        "API_KEY": tok(32),
        "INTERNAL_KEY": tok(32),
        "JWT_SECRET": tok(48),
        "ADMIN_PASSWORD": tok(18),
        "VISIT_HASH_SALT": tok(24),
        "TELEGRAM_WEBHOOK_SECRET": tok(32),
        "HYDROCAST_READONLY_KEY": "hydrocast_PS_V1_" + tok(24),
        "JUPYTER_TOKEN": tok(16),
    }
    s = secrets_map

    text = template
    text = text.replace(
        "postgresql://hms_app:CHANGE_ME@",
        f"postgresql://hms_app:{quote(s['POSTGRES_PASSWORD'], safe='')}@",
    )
    text = text.replace("API_KEY=CHANGE_ME_PUBLIC_API_KEY", f"API_KEY={s['API_KEY']}")
    text = text.replace(
        "INTERNAL_KEY=CHANGE_ME_INTERNAL_SECRET_MIN_16_CHARS",
        f"INTERNAL_KEY={s['INTERNAL_KEY']}",
    )
    text = text.replace(
        "JWT_SECRET=CHANGE_ME_SUPER_SECRET_JWT_KEY_MIN_32_CHARS",
        f"JWT_SECRET={s['JWT_SECRET']}",
    )
    text = text.replace(
        "ADMIN_PASSWORD=change_this_admin_password_in_production",
        f"ADMIN_PASSWORD={s['ADMIN_PASSWORD']}",
    )
    text = text.replace(
        "VISIT_HASH_SALT=CHANGE_ME_RANDOM_SALT", f"VISIT_HASH_SALT={s['VISIT_HASH_SALT']}"
    )
    text = text.replace(
        "TELEGRAM_WEBHOOK_SECRET=CHANGE_ME_TELEGRAM_WEBHOOK_SECRET",
        f"TELEGRAM_WEBHOOK_SECRET={s['TELEGRAM_WEBHOOK_SECRET']}",
    )
    text = re.sub(
        r"(?m)^HYDROCAST_READONLY_KEY=.*$",
        f"HYDROCAST_READONLY_KEY={s['HYDROCAST_READONLY_KEY']}",
        text,
    )

    # Never let a generated file point at a fake production host.
    text = text.replace(
        "CORS_ORIGINS=http://localhost:3000,https://your-dashboard.vercel.app",
        "CORS_ORIGINS=http://localhost:3000,http://127.0.0.1:3000",
    )
    # Neutralise placeholder credentials that would otherwise cause outbound calls.
    text = text.replace(
        "TELEGRAM_BOT_TOKEN=123456:ABCdefGHIjklMNOpqrSTUvwxYZ", "TELEGRAM_BOT_TOKEN="
    )
    text = text.replace(
        "DISASTER_MANAGEMENT_WEBHOOKS=https://alert-dispatch.district.gov.in/api/v1/cwc-hook",
        "DISASTER_MANAGEMENT_WEBHOOKS=",
    )
    text = text.replace("SMTP_PASS=your_app_password", "SMTP_PASS=")

    # docker-compose requires POSTGRES_PASSWORD; keep it identical to the URL.
    if "POSTGRES_PASSWORD=" not in text:
        text = re.sub(
            r"(?m)^(DATABASE_URL=.*)$",
            rf"\1\nPOSTGRES_PASSWORD={s['POSTGRES_PASSWORD']}",
            text,
            count=1,
        )

    header = (
        "# Generated by scripts/bootstrap_env.py on first run.\n"
        "# Do NOT commit. Rotate any value that is ever exposed.\n"
        "# Regenerate: python scripts/bootstrap_env.py --force\n\n"
    )
    return header + text, s


def build_frontend_env(s: dict[str, str]) -> str:
    return (
        "# Generated by scripts/bootstrap_env.py — DO NOT COMMIT.\n"
        "# These must match the backend where noted.\n\n"
        "NODE_ENV=development\n"
        "NEXT_PUBLIC_API_URL=http://localhost:8000\n"
        "NEXT_PUBLIC_WS_URL=ws://localhost:8000/ws/live\n"
        "BACKEND_API_URL=http://localhost:8000\n\n"
        "# Must match backend/.env\n"
        f"API_KEY={s['API_KEY']}\n"
        f"TELEGRAM_WEBHOOK_SECRET={s['TELEGRAM_WEBHOOK_SECRET']}\n\n"
        "# Fill from external providers (blank on purpose):\n"
        "TELEGRAM_BOT_TOKEN=\n"
        "SUPABASE_URL=\n"
        "SUPABASE_SERVICE_ROLE_KEY=\n"
        "NEXT_PUBLIC_SUPABASE_ANON_KEY=\n"
        "KV_REST_API_URL=\n"
        "KV_REST_API_TOKEN=\n"
    )


def _env_values(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def add_missing() -> int:
    """Append only the keys that are absent; never rotate existing secrets."""
    specs = {
        "API_KEY": 32,
        "INTERNAL_KEY": 32,
        "JWT_SECRET": 48,
        "ADMIN_PASSWORD": 18,
        "VISIT_HASH_SALT": 24,
        "TELEGRAM_WEBHOOK_SECRET": 32,
        "HYDROCAST_READONLY_KEY": 32,
        "JUPYTER_TOKEN": 16,
    }
    text = ENV_FILE.read_text(encoding="utf-8") if ENV_FILE.exists() else ""
    # Upgrade an old .env in place: same key, clearer HydroCast name.
    if not re.search(r"(?m)^HYDROCAST_READONLY_KEY=", text) and re.search(
        r"(?m)^HYDROSIM_API_KEY=", text
    ):
        text = re.sub(r"(?m)^HYDROSIM_API_KEY=", "HYDROCAST_READONLY_KEY=", text)
    added: dict[str, str] = {}
    for key, nbytes in specs.items():
        if not re.search(rf"(?m)^{re.escape(key)}=", text):
            added[key] = (
                "hydrocast_PS_V1_" + tok(24)
                if key == "HYDROCAST_READONLY_KEY"
                else tok(nbytes)
            )

    if added:
        text = text.rstrip("\n") + "\n" + "".join(f"{k}={v}\n" for k, v in added.items())
        ENV_FILE.write_text(text, encoding="utf-8", newline="\n")
        try:
            ENV_FILE.chmod(0o600)
        except OSError:
            pass

    # Mirror the shared keys into the frontend file if it is missing them.
    if FRONTEND_ENV.exists():
        values = _env_values(ENV_FILE)
        ftext = FRONTEND_ENV.read_text(encoding="utf-8")
        fmirrored: list[str] = []
        for key in ("API_KEY", "TELEGRAM_WEBHOOK_SECRET"):
            if key in values and not re.search(rf"(?m)^{re.escape(key)}=", ftext):
                ftext = ftext.rstrip("\n") + f"\n{key}={values[key]}\n"
                fmirrored.append(key)
        if fmirrored:
            FRONTEND_ENV.write_text(ftext, encoding="utf-8", newline="\n")

    if not added:
        print("No missing keys — .env is complete.")
    else:
        print(f"Added {len(added)} missing key(s) to {ENV_FILE}:")
        for key, value in added.items():
            print(f"  {key:<24} {mask(value)}")
    if FRONTEND_ENV.exists() and "fmirrored" in locals() and fmirrored:
        print(f"Mirrored into frontend: {', '.join(fmirrored)}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    parser.add_argument(
        "--add-missing",
        action="store_true",
        help="append only keys absent from an existing .env (no rotation)",
    )
    args = parser.parse_args()

    if not ENV_EXAMPLE.exists():
        print(f"ERROR: {ENV_EXAMPLE} not found", file=sys.stderr)
        return 1

    existing = [p for p in (ENV_FILE, FRONTEND_ENV) if p.exists()]
    if existing and not args.force:
        if args.add_missing:
            return add_missing()
        print("Refusing to overwrite existing secret files:")
        for p in existing:
            print(f"  - {p}")
        print("Re-run with --force to rotate everything, or --add-missing to fill gaps.")
        return 2

    template = ENV_EXAMPLE.read_text(encoding="utf-8")
    backend, s = build_backend_env(template)
    ENV_FILE.write_text(backend, encoding="utf-8", newline="\n")
    FRONTEND_ENV.write_text(build_frontend_env(s), encoding="utf-8", newline="\n")

    # Best-effort owner-only permissions on POSIX.
    for p in (ENV_FILE, FRONTEND_ENV):
        try:
            p.chmod(0o600)
        except OSError:
            pass

    print("Wrote:")
    print(f"  {ENV_FILE}")
    print(f"  {FRONTEND_ENV}")
    print("\nGenerated secrets (masked):")
    for key in (
        "POSTGRES_PASSWORD",
        "API_KEY",
        "INTERNAL_KEY",
        "JWT_SECRET",
        "ADMIN_PASSWORD",
        "VISIT_HASH_SALT",
        "TELEGRAM_WEBHOOK_SECRET",
    ):
        print(f"  {key:<24} {mask(s[key])}")
    print(
        "\nAdmin login:  username=admin  password=<see .env ADMIN_PASSWORD>\n"
        "Still blank (get from provider): TELEGRAM_BOT_TOKEN, SMTP_PASS, "
        "Supabase, Upstash, ECMWF."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
